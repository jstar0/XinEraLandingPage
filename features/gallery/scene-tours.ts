import { CatmullRomCurve3, Vector3 } from "three";
import type { GalleryPlace } from "./content";
import { islandTours } from "./tours";

type Point = [number, number, number];

function curve(points: Point[]) {
  const result = new CatmullRomCurve3(
    points.map((point) => new Vector3(...point)),
    true,
    "centripetal",
  );
  result.arcLengthDivisions = 480;
  return result;
}

function route(duration: number, eye: Point[], target: Point[]) {
  return { duration, eye: curve(eye), target: curve(target) };
}

